import { createHash, randomUUID } from 'node:crypto';
import { createReadStream } from 'node:fs';
import fs from 'node:fs/promises';
import type { Readable } from 'node:stream';
import { fileTypeFromFile } from 'file-type';
import { parseFile } from 'music-metadata';
import sharp from 'sharp';
import { prisma } from '../../config/prisma';
import type { Prisma } from '../../generated/prisma/client';
import { AppError, notFound } from '../../lib/errors';
import { storage } from '../../lib/storage';
import type { ByteRange } from '../../lib/storage/storage';
import type { FileDto } from '../../shared/admin';
import type { FilePurpose, Role } from '../../shared/enums';

/** Allowed detected types per purpose (magic bytes, never the client header). SVG/GIF/HEIC are never accepted. */
const ALLOWED: Record<FilePurpose, Record<string, string>> = {
  TEST_AUDIO: { mp3: 'audio/mpeg', m4a: 'audio/mp4', mp4: 'audio/mp4', wav: 'audio/wav', ogg: 'audio/ogg' },
  TEST_IMAGE: { png: 'image/png', jpg: 'image/jpeg', webp: 'image/webp' },
  OCR_SOURCE: { png: 'image/png', jpg: 'image/jpeg', webp: 'image/webp', pdf: 'application/pdf' },
  OCR_PAGE: { png: 'image/png' },
  SPEAKING_RECORDING: {
    webm: 'audio/webm',
    ogg: 'audio/ogg',
    m4a: 'audio/mp4',
    mp4: 'audio/mp4',
    wav: 'audio/wav',
  },
};

export interface StoredFileRow {
  id: string;
  purpose: FilePurpose;
  storageKey: string;
  mimeType: string;
  originalName: string | null;
  sizeBytes: number;
  widthPx: number | null;
  heightPx: number | null;
  durationMs: number | null;
  createdAt: Date;
}

export const toFileDto = (f: StoredFileRow): FileDto => ({
  id: f.id,
  purpose: f.purpose,
  mimeType: f.mimeType,
  originalName: f.originalName,
  sizeBytes: f.sizeBytes,
  widthPx: f.widthPx,
  heightPx: f.heightPx,
  durationMs: f.durationMs,
  createdAt: f.createdAt.toISOString(),
});

async function sha256OfFile(path: string): Promise<string> {
  const hash = createHash('sha256');
  for await (const chunk of createReadStream(path)) hash.update(chunk as Buffer);
  return hash.digest('hex');
}

function sanitizeName(name: string | undefined): string | null {
  if (!name) return null;
  // eslint-disable-next-line no-control-regex -- strip control characters from client file names
  const clean = name.replace(/[\\/:*?"<>|\u0000-\u001f]/g, '_').slice(-200);
  return clean || null;
}

export const filesService = {
  /**
   * Validate (magic bytes) + store one uploaded temp file. Re-uses an existing file with the same content and
   * purpose (sha256), so importing the same asset twice does not duplicate it.
   */
  async ingest(input: {
    path: string;
    purpose: FilePurpose;
    originalName?: string;
    uploadedById?: string | null;
  }): Promise<StoredFileRow> {
    const detected = await fileTypeFromFile(input.path);
    const allowed = ALLOWED[input.purpose];
    const mimeType = detected ? allowed[detected.ext] : undefined;
    if (!detected || !mimeType) {
      throw new AppError(
        'FILE_SIGNATURE_MISMATCH',
        `Loại file không được phép (chỉ nhận: ${Object.keys(allowed).join(', ')})`,
      );
    }
    const sha256 = await sha256OfFile(input.path);
    const existing = await prisma.storedFile.findFirst({ where: { sha256, purpose: input.purpose } });
    if (existing) return existing;

    let widthPx: number | null = null;
    let heightPx: number | null = null;
    let durationMs: number | null = null;
    if (mimeType.startsWith('image/')) {
      const meta = await sharp(input.path).metadata();
      widthPx = meta.width;
      heightPx = meta.height;
      if (widthPx > 10_000 || heightPx > 10_000)
        throw new AppError('VALIDATION_ERROR', 'Ảnh quá lớn (tối đa 10 000 px)');
    } else if (mimeType.startsWith('audio/')) {
      const meta = await parseFile(input.path, { duration: true }).catch(() => null);
      const seconds = meta?.format.duration;
      durationMs = seconds ? Math.round(seconds * 1000) : null;
    }

    const now = new Date();
    const storageKey = `${input.purpose.toLowerCase().replace(/_/g, '-')}/${now.getUTCFullYear()}/${String(now.getUTCMonth() + 1).padStart(2, '0')}/${randomUUID()}.${detected.ext}`;
    const { size } = await fs.stat(input.path);
    await storage.put(storageKey, createReadStream(input.path));
    try {
      return await prisma.storedFile.create({
        data: {
          storageKey,
          purpose: input.purpose,
          mimeType,
          originalName: sanitizeName(input.originalName),
          sizeBytes: size,
          sha256,
          widthPx,
          heightPx,
          durationMs,
          uploadedById: input.uploadedById ?? null,
        },
      });
    } catch (err) {
      await storage.delete(storageKey);
      throw err;
    }
  },

  /** Store bytes generated by the server itself (e.g. rasterized OCR pages). */
  async storeGenerated(input: {
    bytes: Buffer;
    purpose: FilePurpose;
    ext: string;
    mimeType: string;
    widthPx?: number;
    heightPx?: number;
    uploadedById?: string | null;
  }): Promise<StoredFileRow> {
    const sha256 = createHash('sha256').update(input.bytes).digest('hex');
    const now = new Date();
    const storageKey = `${input.purpose.toLowerCase().replace(/_/g, '-')}/${now.getUTCFullYear()}/${String(now.getUTCMonth() + 1).padStart(2, '0')}/${randomUUID()}.${input.ext}`;
    await storage.put(storageKey, input.bytes);
    return prisma.storedFile.create({
      data: {
        storageKey,
        purpose: input.purpose,
        mimeType: input.mimeType,
        sizeBytes: input.bytes.length,
        sha256,
        widthPx: input.widthPx ?? null,
        heightPx: input.heightPx ?? null,
        uploadedById: input.uploadedById ?? null,
      },
    });
  },

  async list(q: { purpose?: FilePurpose; page: number; pageSize: number }) {
    const where: Prisma.StoredFileWhereInput = q.purpose ? { purpose: q.purpose } : {};
    const [rows, total] = await Promise.all([
      prisma.storedFile.findMany({
        where,
        orderBy: { createdAt: 'desc' },
        skip: (q.page - 1) * q.pageSize,
        take: q.pageSize,
      }),
      prisma.storedFile.count({ where }),
    ]);
    return { items: rows.map(toFileDto), page: q.page, pageSize: q.pageSize, total };
  },

  /** FK `Restrict` refuses deleting a file still referenced by a test. */
  async remove(id: string): Promise<void> {
    const f = await prisma.storedFile.findUnique({ where: { id } });
    if (!f) throw notFound('File');
    try {
      await prisma.storedFile.delete({ where: { id } });
    } catch {
      throw new AppError('CONFLICT', 'File đang được dùng trong một đề, không xóa được', {
        reason: 'IN_USE',
      });
    }
    await storage.delete(f.storageKey);
  },

  /**
   * Who may read a file: admins everything; students only test media of a published test (or of a test they
   * have an attempt on) and their own uploads (speaking recordings). Anything else → 404 (do not reveal it exists).
   */
  async findReadable(id: string, actor: { id: string; role: Role }): Promise<StoredFileRow> {
    const f = await prisma.storedFile.findUnique({ where: { id } });
    if (!f) throw notFound('File');
    if (actor.role === 'ADMIN') return f;
    if (f.purpose === 'SPEAKING_RECORDING' && f.uploadedById === actor.id) return f;
    if (f.purpose === 'TEST_AUDIO' || f.purpose === 'TEST_IMAGE') {
      const visibleTest: Prisma.TestWhereInput = {
        OR: [{ status: 'PUBLISHED' }, { attempts: { some: { userId: actor.id } } }],
      };
      const inSection = { section: { test: visibleTest } };
      const used = await prisma.storedFile.count({
        where: {
          id,
          OR: [
            { audios: { some: { part: inSection } } },
            { writingTaskImages: { some: { part: inSection } } },
            { questionGroupImages: { some: { part: inSection } } },
            { paragraphImages: { some: { passage: { part: inSection } } } },
          ],
        },
      });
      if (used > 0) return f;
    }
    throw notFound('File');
  },

  open(f: StoredFileRow, range?: ByteRange): Promise<Readable> {
    return storage.getStream(f.storageKey, range);
  },

  async readBuffer(f: { storageKey: string }): Promise<Buffer> {
    const chunks: Buffer[] = [];
    for await (const c of await storage.getStream(f.storageKey)) chunks.push(c as Buffer);
    return Buffer.concat(chunks);
  },
};
